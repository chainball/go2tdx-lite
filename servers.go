func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	b := [4]byte{}
	i := len(b)
	for n > 0 {
		i--
		b[i] = byte('0' + n%10)
		n /= 10
	}
	return string(b[i:])
}

